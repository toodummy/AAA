// Drives the UI harness with real clicks and keys and asserts the right actions fire.
// Usage: node tools/test-ui-interact.mjs   (needs: npx vite --port 5202 --strictPort)
import { chromium } from 'playwright-core';

const BASE = 'http://127.0.0.1:5202/tools/ui.html';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1238, height: 802 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
let pass = 0;
let fail = 0;
const ok = (cond, label) => { if (cond) { pass++; console.log('  ok   ' + label); } else { fail++; console.log('  FAIL ' + label); } };
const open = async (query) => { await page.goto(`${BASE}?${query}`); await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(600); await page.evaluate(() => { window.__uiDemo.calls.length = 0; }); };
const calls = () => page.evaluate(() => window.__uiDemo.calls.filter((c) => c.name !== 'audio').map((c) => c.name + '(' + c.args.map((a) => JSON.stringify(a)).join(',') + ')'));
const sounds = () => page.evaluate(() => window.__uiDemo.calls.filter((c) => c.name === 'audio').map((c) => c.args[0]));
const last = async () => { const c = await calls(); return c[c.length - 1] || ''; };
const clear = () => page.evaluate(() => { window.__uiDemo.calls.length = 0; });
const screen = () => page.evaluate(() => document.getElementById('ui').dataset.screen);
const focusKey = () => page.evaluate(() => (document.activeElement && document.activeElement.dataset.key) || '');
const key = async (k, n = 1) => { for (let i = 0; i < n; i++) { await page.keyboard.press(k); await page.waitForTimeout(40); } };
const click = async (sel) => { await page.click('.is-on ' + sel); await page.waitForTimeout(80); };

console.log('title');
await open('screen=title');
await key('KeyX');
ok((await last()) === 'titleContinue()', 'any key -> titleContinue');
ok((await screen()) === 'menu', 'mock game switched to menu');
await open('screen=title');
await page.mouse.click(600, 400);
ok((await last()) === 'titleContinue()', 'click -> titleContinue');

