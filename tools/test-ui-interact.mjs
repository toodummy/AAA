for (let i = 0; i < 5 && (await focusKey()) !== 'storm:classic'; i++) await key('ArrowLeft');
ok((await focusKey()) === 'storm:classic', 'ArrowLeft walks to the first storm');
await key('ArrowRight', 3);
ok((await focusKey()) === 'storm:snow', 'ArrowRight walks to a locked storm');
ok(await page.evaluate(() => document.querySelector('[data-key="start"]').classList.contains('is-disabled')), 'START disabled for locked storm');
ok((await page.textContent('.sz-storm-req')).includes('Defeat AEGIS'), 'locked storm shows unlock text');
await key('ArrowDown'); await key('Enter');
ok((await calls()).length === 0, 'Enter on locked START does nothing');
await key('ArrowUp'); for (let i = 0; i < 5 && (await focusKey()) !== 'storm:fire'; i++) await key('ArrowLeft'); await key('ArrowDown');
ok((await focusKey()) === 'start', 'back down to START');
await key('Enter');
ok((await last()) === 'startRun("fire")', 'Enter -> startRun("fire"): ' + (await last()));

console.log('menu / tabs + upgrades (keyboard only)');
await open('screen=menu');
await key('Escape');
ok((await focusKey()) === 'tab:play', 'Escape returns focus to the tab rail');
await key('ArrowDown');
ok(await page.evaluate(() => document.querySelector('[data-page="upgrades"]').classList.contains('is-on')), 'ArrowDown on rail switches to UPGRADES');
await key('ArrowRight');
ok((await focusKey()) === 'meta:startMass', 'ArrowRight enters the panel: ' + (await focusKey()));
await key('Enter');
ok((await last()) === 'buyMeta("startMass")', 'Enter -> buyMeta("startMass")');
await page.waitForTimeout(100);
ok((await focusKey()) === 'meta:startMass', 'focus kept after the shop re-renders');
ok((await page.textContent('[data-r="balance"]')) === '1,000', 'balance updated to 1,000: ' + (await page.textContent('[data-r="balance"]')));
await clear();
await key('ArrowRight'); // Thick Skin (maxed)
await key('Enter');
ok((await calls()).length === 0, 'maxed upgrade cannot be bought');
await key('ArrowDown', 3);
ok((await focusKey()) === 'meta:revive', 'grid navigation reaches Eye Wall: ' + (await focusKey()));
await key('Enter');
ok((await calls()).length === 0, 'unaffordable upgrade cannot be bought');
await key('ArrowLeft', 2);
ok((await focusKey()) === 'tab:upgrades', 'ArrowLeft returns to the active tab: ' + (await focusKey()));

console.log('menu / settings');
await open('screen=menu&tab=settings');
ok((await focusKey()) === 'set:master', 'first setting focused');
await key('ArrowRight');
ok((await last()) === 'setSetting("master",0.9)', 'ArrowRight on slider -> ' + (await last()));
await key('ArrowDown', 3); await key('ArrowRight');
ok((await last()) === 'setSetting("quality","ultra")', 'ArrowRight on quality -> ' + (await last()));
await key('ArrowDown', 2); await key('Enter');
ok((await last()) === 'toggleFullscreen()', 'Enter on fullscreen -> toggleFullscreen()');
await key('ArrowDown'); await key('Enter');
ok((await last()) === 'setSetting("mouseSteer",false)', 'Enter on toggle -> ' + (await last()));
await click('[data-set="showFps"]');
ok((await last()) === 'setSetting("showFps",false)', 'click toggle -> ' + (await last()));
await click('[data-set="quality"] [data-opt="low"]');
ok((await last()) === 'setSetting("quality","low")', 'click segment -> ' + (await last()));
const box = await page.locator('.sz-menu [data-set="music"] [data-slider]').boundingBox();
await page.mouse.click(box.x + box.width * 0.25, box.y + box.height / 2);
ok((await last()) === 'setSetting("music",0.25)', 'click slider track -> ' + (await last()));
await page.mouse.move(box.x + box.width * 0.25, box.y + box.height / 2); await page.mouse.down(); await page.mouse.move(box.x + box.width * 0.75, box.y + box.height / 2, { steps: 4 }); await page.mouse.up();
ok((await last()) === 'setSetting("music",0.75)', 'drag slider -> ' + (await last()));
await clear();
await click('[data-act="askReset"]');
ok((await focusKey()) === 'modal-no', 'reset confirm opens with Cancel focused');
await key('Escape');
ok((await calls()).length === 0 && !(await page.evaluate(() => document.querySelector('.sz-modal').classList.contains('is-on'))), 'Escape cancels the confirm');
await click('[data-act="askReset"]'); await key('ArrowRight'); await key('Enter');
ok((await last()) === 'resetSave()', 'confirm -> resetSave()');
await clear();
await click('[data-act="quitApp"]'); await click('[data-act="modalYes"]');
ok((await last()) === 'quitApp()', 'Quit -> confirm -> quitApp()');
await open('screen=menu&noquit=1');
ok((await page.locator('[data-act="quitApp"]').count()) === 0, 'Quit hidden when actions.quitApp is undefined');
for (const tab of ['achievements', 'howto', 'credits', 'play']) {
  await click(`[data-tab="${tab}"]`);
  ok(await page.evaluate((t) => document.querySelector(`[data-page="${t}"]`).classList.contains('is-on'), tab), 'click tab ' + tab);
}
await click('[data-storm="shark"]'); await click('[data-act="start"]');
ok((await last()) === 'startRun("shark")', 'mouse: pick storm + START -> ' + (await last()));

console.log('hud');
await open('screen=hud&freeze=1&tier=3');
ok(await page.evaluate(() => document.elementFromPoint(600, 400).id === 'game'), 'empty HUD area lets the mouse through to the game');
for (const ab of ['dash', 'fling', 'ult']) { await click(`[data-ab="${ab}"]`); ok((await last()) === `ability("${ab}")`, 'click ability -> ' + (await last())); }
ok(await page.evaluate(() => !document.activeElement || document.activeElement === document.body), 'HUD buttons do not steal keyboard focus');
await clear(); await key('Enter'); await key('ArrowLeft'); await key('Escape');
ok((await calls()).length === 0, 'UI ignores keys while on the HUD (game owns them)');
await page.click('.sz-pausebtn'); await page.waitForTimeout(80);
