await open('screen=pause&freeze=1&tier=3');
await key('ArrowDown', 2); await key('Enter');
ok((await focusKey()) === 'set:master', 'Settings opens inside pause');
await key('ArrowLeft');
ok((await last()) === 'setSetting("master",0.7)', 'pause settings adjust -> ' + (await last()));
await key('Escape');
ok((await focusKey()) === 'psettings' && (await screen()) === 'pause', 'Escape goes back to the pause menu');
await key('ArrowDown'); await key('Enter'); await click('[data-act="modalYes"]');
ok((await last()) === 'quitToMenu()' && (await screen()) === 'menu', 'Quit to menu -> confirm -> quitToMenu()');
await open('screen=pause&freeze=1&tier=3');
await click('[data-act="resume"]');
ok((await last()) === 'resume()', 'click Resume -> resume()');

console.log('level-up');
await page.goto(`${BASE}?screen=levelup&freeze=1&tier=3&mut=1&cards=4`);
await page.waitForTimeout(120);
