console.log('audio + lifecycle');
const snd = new Set();
await open('screen=menu'); await key('ArrowUp'); await key('Enter'); await key('Escape'); (await sounds()).forEach((s) => snd.add(s));
await open('screen=levelup&freeze=1&tier=3'); (await page.evaluate(() => { window.__uiDemo.show('levelup'); })); await page.waitForTimeout(450); await key('Digit1'); (await sounds()).forEach((s) => snd.add(s));
for (const s of ['ui_hover', 'ui_click', 'ui_back', 'card_show', 'card_pick']) ok(snd.has(s), 'audio.play("' + s + '")');
const leak = await page.evaluate(() => { const before = Object.keys(window).length; window.__uiDemo.ui.toast('x', 'info'); window.__uiDemo.ui.news('y'); window.__uiDemo.ui.popup(.5, .5, '1', 'xp'); window.__uiDemo.ui.flash('hurt'); window.__uiDemo.ui.destroy(); window.__uiDemo.ui.updateHud(window.__uiDemo.hud); window.__uiDemo.ui.setScreen('menu'); return { grew: Object.keys(window).length - before, html: document.getElementById('ui').innerHTML.length, cls: document.getElementById('ui').className }; });
ok(leak.html === 0 && leak.cls === '' && leak.grew === 0, 'destroy() empties the root, later calls are no-ops, no globals added');
ok(errors.length === 0, 'no page errors' + (errors.length ? ': ' + errors.join(' | ') : ''));

await browser.close();
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
